#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const postsDir = path.join(root, 'public/posts');

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.gif', '.webp']);
const VIDEO_EXT = new Set(['.mov', '.mp4', '.webm']);

function mediaKind(name) {
  const ext = path.extname(name).toLowerCase();
  if (VIDEO_EXT.has(ext)) return 'video';
  if (IMAGE_EXT.has(ext)) return 'image';
  return null;
}

const files = fs
  .readdirSync(postsDir, { encoding: 'utf8' })
  .filter((f) => !f.startsWith('.') && mediaKind(f))
  .sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));

const items = files.map((filename, index) => ({
  id: `media-${index + 1}`,
  filename,
  kind: mediaKind(filename),
}));

const out = `/** Auto-generated by scripts/sync-gallery-media.mjs — do not edit by hand */
export type GalleryMediaKind = 'image' | 'video';

export type GalleryMediaItem = {
  id: string;
  filename: string;
  kind: GalleryMediaKind;
};

export const GALLERY_MEDIA: GalleryMediaItem[] = ${JSON.stringify(items, null, 2)};

export const GALLERY_IMAGE_COUNT = GALLERY_MEDIA.filter((m) => m.kind === 'image').length;
export const GALLERY_VIDEO_COUNT = GALLERY_MEDIA.filter((m) => m.kind === 'video').length;
export const GALLERY_MEDIA_COUNT = GALLERY_MEDIA.length;
`;

fs.writeFileSync(path.join(root, 'src/data/gallery-media.ts'), out);
console.log('Wrote', items.length, 'items (', items.filter((i) => i.kind === 'image').length, 'images,', items.filter((i) => i.kind === 'video').length, 'videos)');
