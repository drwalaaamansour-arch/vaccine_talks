#!/usr/bin/env node
/** Generate src/lib/generatedSiteStats.ts from public page routes in src/app. */
import fs from 'fs';
import path from 'path';

const ROOT = path.resolve(import.meta.dirname, '..');
const APP_DIR = path.join(ROOT, 'src/app');
const OUTPUT_PATH = path.join(ROOT, 'src/lib/generatedSiteStats.ts');

// Keep in sync with src/lib/sitemap-routes.ts
const EXCLUDED_PREFIXES = ['/api', '/auth', '/copy', '/_not-found'];
const EXCLUDED_EXACT = new Set(['']);

const DYNAMIC_ROUTES = {
  '/non-hcp/special-cases-vaccines': [
    'preterm-infants',
    'pregnancy-and-breastfeeding',
    'post-cochlear-implant',
    'splenectomy',
    'during-and-after-chemotherapy',
    'post-bone-marrow-transplant',
    'immune-disease-patients',
    'immunosuppressive-medications',
  ],
};

function shouldExclude(route) {
  if (!route || EXCLUDED_EXACT.has(route)) return true;
  return EXCLUDED_PREFIXES.some(
    (prefix) => route === prefix || route.startsWith(`${prefix}/`),
  );
}

function collectStaticRoutes(dir, base = '') {
  if (!fs.existsSync(dir)) return [];

  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const routes = [];

  for (const entry of entries) {
    if (entry.name.startsWith('.') || entry.name === 'api') continue;

    const fullPath = path.join(dir, entry.name);
    const routePath = `${base}/${entry.name}`.replace(/\/+/g, '/');

    if (entry.isDirectory()) {
      if (entry.name.startsWith('[') && entry.name.endsWith(']')) {
        const parentRoute = base || '/';
        const slugs = DYNAMIC_ROUTES[parentRoute];
        if (slugs) {
          for (const slug of slugs) {
            const dynamicRoute = `${parentRoute}/${slug}`.replace(/\/+/g, '/');
            if (!shouldExclude(dynamicRoute)) routes.push(dynamicRoute);
          }
        }
        continue;
      }

      routes.push(...collectStaticRoutes(fullPath, routePath));
      continue;
    }

    if (entry.name === 'page.tsx' || entry.name === 'page.ts') {
      const route = base || '/';
      if (!shouldExclude(route)) routes.push(route);
    }
  }

  return routes;
}

function getPublicRoutes() {
  const routes = collectStaticRoutes(APP_DIR);
  return [...new Set(routes)].sort();
}

function isHcpRoute(route) {
  return (
    route.startsWith('/hcp/') ||
    route.startsWith('/hcp-') ||
    route.startsWith('/faq') ||
    route.startsWith('/doc')
  );
}

function isFaqRoute(route) {
  return route.startsWith('/faq') || route.startsWith('/non-hcp/common-questions');
}

function isSpecialPopulationRoute(route) {
  return (
    route.startsWith('/hcp-special-populations') ||
    route.startsWith('/non-hcp/special-cases-vaccines')
  );
}

function getSiteStats() {
  const routes = getPublicRoutes();
  const hcpPages = routes.filter(isHcpRoute).length;

  return {
    totalPages: routes.length,
    hcpPages,
    parentPages: routes.length - hcpPages,
    faqPages: routes.filter(isFaqRoute).length,
    specialPopulationPages: routes.filter(isSpecialPopulationRoute).length,
  };
}

const siteStats = getSiteStats();

const output = `/** Auto-generated by scripts/generate-site-stats.mjs — do not edit manually. */
export const siteStats = {
  totalPages: ${siteStats.totalPages},
  hcpPages: ${siteStats.hcpPages},
  parentPages: ${siteStats.parentPages},
  faqPages: ${siteStats.faqPages},
  specialPopulationPages: ${siteStats.specialPopulationPages},
} as const;
`;

fs.writeFileSync(OUTPUT_PATH, output, 'utf8');

console.log(`Wrote ${path.relative(ROOT, OUTPUT_PATH)}`);
console.log(JSON.stringify(siteStats, null, 2));
